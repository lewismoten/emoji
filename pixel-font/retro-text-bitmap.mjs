function toMatrix(bitmap) {
  return Array.from({ length: 7 }, (_, row) =>
    bitmap.slice(row * 5, row * 5 + 5).split(""),
  );
}

function fromMatrix(matrix) {
  return matrix.map((row) => row.join("")).join("");
}

function overlay(base, accent, shift = 1) {
  const baseMatrix = toMatrix(base);
  const accentMatrix = toMatrix(accent);
  const result = Array.from({ length: 7 }, (_, row) => Array(5).fill("0"));
  for (let row = 0; row < 7; row += 1) {
    const sourceRow = row - shift;
    if (sourceRow >= 0 && sourceRow < 7)
      result[row] = [...baseMatrix[sourceRow]];
  }
  for (let row = 0; row < 7; row += 1) {
    for (let column = 0; column < 5; column += 1) {
      if (accentMatrix[row][column] === "1") result[row][column] = "1";
    }
  }
  return fromMatrix(result);
}

