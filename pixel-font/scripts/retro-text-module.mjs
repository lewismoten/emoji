import fs from "node:fs/promises";
import { format } from "prettier";

function escapeCharacter(character) {
  return JSON.stringify(character);
}

function escapeBitmap(bitmap) {
  return JSON.stringify(bitmap);
}

export async function writeRetroTextBitmapModule(
  glyphs,
  outputFile,
  sourceLabel = "retro-text atlas sources",
) {
  const entries = [...glyphs]
    .sort((left, right) => left.character.localeCompare(right.character))
    .map(
      ({ bitmap, character }) =>
        `  ${escapeCharacter(character)}: ${escapeBitmap(bitmap)},`,
    );
  const characters = [...glyphs]
    .map(({ character }) => character)
    .sort((left, right) => left.localeCompare(right))
    .map((character) => `  ${escapeCharacter(character)},`);

  const contents = [
    `// Generated from ${sourceLabel}.`,
    "// Do not edit this file directly; edit the atlas PNG/JSON sources instead.",
    "",
    "export const BITMAP_FONT_5X7 = Object.freeze({",
    ...entries,
    "});",
    "",
    "export const BITMAP_FONT_5X7_CHARACTERS = Object.freeze([",
    ...characters,
    "]);",
    "",
  ].join("\n");

  await fs.writeFile(
    outputFile,
    await format(contents, { parser: "babel" }),
  );
}
